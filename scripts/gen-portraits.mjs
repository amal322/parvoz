// Builds src/data/portraits.ts: illustrated placeholder portraits (DiceBear "Notionists" by Zoish, CC0).
// Real student photos come from the Digital CV once the registrar feed is connected.
import { createAvatar } from '@dicebear/core'
import { notionists } from '@dicebear/collection'
import { optimize } from 'svgo'
import { writeFileSync } from 'node:fs'

const v = (xs) => xs.map((n) => 'variant' + String(n).padStart(2, '0'))
const HAIR = {
  f: v([63, 58, 48, 47, 46, 43, 41, 39, 37, 36, 28, 23, 10, 8, 4, 2, 62, 45, 11, 29]),
  m: v([56, 55, 54, 53, 52, 49, 44, 38, 35, 34, 33, 32, 31, 27, 25, 24, 22, 21, 19, 18]),
}
const N = 20
const make = (g, i) => {
  const svg = createAvatar(notionists, {
    seed: `parvoz-${g}-${i}`,
    hair: [HAIR[g][i % HAIR[g].length]],
    lips: [v([3, 5, 17, 22, 14])[i % 5]],
    glasses: [v([11, 8, 3])[i % 3]],
    eyes: [v([4, 5])[i % 2]],
    brows: [v([1, 12, 5])[i % 3]],
    beardProbability: g === 'm' && i % 6 === 3 ? 100 : 0,
    glassesProbability: i % 4 === 1 ? 100 : 0,
    gestureProbability: 0,
    bodyIconProbability: 0,
  }).toString()
  return optimize(svg, { multipass: true, floatPrecision: 1 }).data
}
const out = { f: [], m: [] }
for (const g of ['f', 'm']) for (let i = 0; i < N; i++) out[g].push(make(g, i))
const size = JSON.stringify(out).length
writeFileSync('src/data/portraits.ts', `// Generated by scripts/gen-portraits.mjs. Do not edit.\nexport const PORTRAITS: { f: string[]; m: string[] } = ${JSON.stringify(out)}\n`)
console.log('portraits', (size / 1024).toFixed(0) + ' KB')
