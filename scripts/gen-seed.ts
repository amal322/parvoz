// Builds supabase/seed.sql from the same demo data the prototype uses (src/data/seed.ts).
import { writeFileSync } from 'node:fs'
import { COMPANY, JOBS, OTHER_COMPANIES, ROLES, STUDENTS } from '../src/data/seed'
import { insightOf } from '../src/data/insight'
import { translate } from '../src/i18n'

const en = (k: string) => translate('en', k)
const q = (s: string | number | null) => (s === null ? 'null' : typeof s === 'number' ? String(s) : `'${s.replace(/'/g, "''")}'`)
const nums = (xs: number[]) => `'{${xs.join(',')}}'`
const arr = (xs: string[]) => `'{${xs.map((x) => (/[ ,()/]/.test(x) ? `"${x}"` : x)).join(',')}}'`
const SCHOOL = { eng: 'engineering', bus: 'business', med: 'medical', den: 'dental' } as const
const EMP = { full: 'full_time', intern: 'internship', part: 'part_time' } as const
const PREFIX = { eng: 'ENG', bus: 'BUS', med: 'MED', den: 'DEN' } as const

const count: Record<string, number> = {}
const students = STUDENTS.map((s) => {
  count[s.school] = (count[s.school] ?? 0) + 1
  const [first, last] = s.name.toLowerCase().split(' ')
  const ins = insightOf(s)
  return `  (${[
    q(`${PREFIX[s.school]}-${String(count[s.school]).padStart(4, '0')}`), q(s.name), q(SCHOOL[s.school]), q(en('prog.' + s.program)), s.year, s.gradYear,
    s.gpa.toFixed(2), s.attendance, s.cvScore, arr(s.openTo.map((o) => EMP[o])), q(s.availableFrom), s.salary, q(s.english), arr(s.langs),
    q((s.female ? 'f' : 'm') + s.portrait), q(en('hl.' + s.program)), q(`${first[0]}.${last}@students.example`), arr(s.skills),
    nums(s.skills.map((k) => ins.levels[k])), ins.score.acad, ins.score.proj, ins.score.act, nums(ins.terms.map((t) => t.gpa)), nums(ins.terms.map((t) => t.att)),
  ].join(', ')})`
})

const programs = [...new Set(STUDENTS.map((s) => s.program))]
const faculty: Record<string, string[]> = {}
for (const s of STUDENTS) (faculty[s.program] ??= []).push(...s.projects.map((p) => p.gradedBy))
const projects = programs.flatMap((p) => [1, 2].map((n) => `  (${q(en('prog.' + p))}, ${q(en(`pj.${p}.${n}.t`))}, ${q(en(`pj.${p}.${n}.d`))}, ${q(faculty[p][n - 1] ?? faculty[p][0])})`))

const companies = [{ name: COMPANY.name, industry: COMPANY.industry, plan: 'team', status: 'approved' }, ...OTHER_COMPANIES]
const tin = (i: number) => `DEMO-${String(i + 1).padStart(4, '0')}`
const roles = [...ROLES.map((r) => ({ ...r, company: COMPANY.name })), ...JOBS]

const sql = `-- Parvoz · demo data. Every person and company here is invented.
-- Generated by scripts/gen-seed.ts from src/data/seed.ts. Safe to run more than once.
begin;
set local search_path = parvoz;

insert into companies (name, tin, industry, status) values
${companies.map((c, i) => `  (${q(c.name)}, ${q(tin(i))}, ${q(en('ind.' + c.industry))}, ${q(c.status)})`).join(',\n')}
on conflict (tin) do nothing;

insert into subscriptions (company_id, plan_code)
select c.id, v.plan from (values
${companies.filter((c) => c.status === 'approved').map((c) => `  (${q(tin(companies.indexOf(c)))}, ${q(c.plan)})`).join(',\n')}
) as v (tin, plan)
join companies c on c.tin = v.tin
where not exists (select 1 from subscriptions s where s.company_id = c.id);

create temp table demo_students (
  student_no text, full_name text, school text, program text, year_of_study int, grad_year int, gpa numeric, attendance_pct int, cv_score int,
  open_to text[], available_from date, salary bigint, english text, langs text[], portrait text, headline text, email text, skills text[],
  skill_levels int[], score_academic int, score_projects int, score_activity int, term_gpa numeric[], term_att int[]
) on commit drop;
insert into demo_students values
${students.join(',\n')};

insert into students (student_no, full_name, school, program, year_of_study, grad_year, gpa, attendance_pct, cv_score, open_to, available_from,
                      salary_expectation_uzs, english, langs, portrait, headline, email, visible, consent_at)
select student_no, full_name, school::school, program, year_of_study, grad_year, gpa, attendance_pct, cv_score, open_to::employment_type[], available_from,
       salary, english, langs, portrait, headline, email, true, now()
from demo_students
on conflict (student_no) do nothing;

insert into skills (name) select distinct unnest(skills) from demo_students on conflict (name) do nothing;

insert into student_skills (student_id, skill_id, verified)
select s.id, k.id, true
from demo_students d
join students s on s.student_no = d.student_no
cross join lateral unnest(d.skills) as u (name)
join skills k on k.name = u.name
on conflict do nothing;

-- the record behind the profile charts (migration 0003); fills only what is still empty
update students s
set score_academic = d.score_academic, score_projects = d.score_projects, score_activity = d.score_activity
from demo_students d
where s.student_no = d.student_no and s.score_academic is null;

update student_skills ss
set level = u.level
from demo_students d
join students s on s.student_no = d.student_no
cross join lateral unnest(d.skills, d.skill_levels) as u (name, level)
join skills k on k.name = u.name
where ss.student_id = s.id and ss.skill_id = k.id and ss.level is null;

insert into student_terms (student_id, term, gpa, attendance_pct)
select s.id, u.term, u.gpa, u.att
from demo_students d
join students s on s.student_no = d.student_no
cross join lateral unnest(d.term_gpa, d.term_att) with ordinality as u (gpa, att, term)
on conflict do nothing;

create temp table demo_projects (program text, title text, summary text, graded_by text) on commit drop;
insert into demo_projects values
${projects.join(',\n')};

insert into projects (student_id, title, summary, verified_by)
select s.id, p.title, p.summary, p.graded_by
from demo_students d
join students s on s.student_no = d.student_no
join demo_projects p on p.program = d.program
on conflict (student_id, title) do nothing;

insert into job_roles (company_id, title, schools, skills, employment, salary_min, salary_max)
select c.id, v.title, v.schools::school[], v.skills, v.employment::employment_type, v.salary_min, v.salary_max
from (values
${roles.map((r) => `  (${q(r.company!)}, ${q(en(r.titleKey!))}, ${arr(r.schools.map((x) => SCHOOL[x]))}, ${arr(r.skills)}::text[], ${q(EMP[r.employment])}, ${r.salaryMin}::bigint, ${r.salaryMax}::bigint)`).join(',\n')}
) as v (company, title, schools, skills, employment, salary_min, salary_max)
join companies c on c.name = v.company and c.tin like 'DEMO-%'
where not exists (select 1 from job_roles r where r.company_id = c.id and r.title = v.title);

commit;
`
writeFileSync('supabase/seed.sql', sql)
console.log('supabase/seed.sql', (sql.length / 1024).toFixed(1) + ' KB,', students.length, 'students,', roles.length, 'roles')
