const MLN: Record<Lang, string> = { en: 'M', ru: ' млн', uz: ' mln' }

export type Vars = Record<string, string | number>
export function translate(lang: Lang, key: string, vars?: Vars): string {
  const e = D[key]
  let s = e ? e[IDX[lang]] : key
  if (vars) for (const k in vars) s = s.split(`{${k}}`).join(String(vars[k]))
  return s
}
export const hasKey = (key: string) => key in D
export const allKeys = () => Object.keys(D)

const group = (n: number) => Math.round(n).toString().replace(/\B(?=(\d{3})+(?!\d))/g, ' ')
const utc = (iso: string) => new Date(iso.length === 7 ? iso + '-01T00:00:00Z' : iso.length === 10 ? iso + 'T00:00:00Z' : iso + ':00Z')

export function makeT(lang: Lang) {
  const dec = (n: number) => {
    const s = Number.isInteger(n) ? String(n) : n.toFixed(1)
    return lang === 'en' ? s : s.replace('.', ',')
  }
  const t = (key: string, vars?: Vars) => translate(lang, key, vars)
  // own month and weekday names: browsers do not all ship Uzbek locale data
  const M = MONTHS[lang], d = (iso: string) => utc(iso)
  const day = (x: Date) => (lang === 'uz' ? `${x.getUTCDate()}-${M.short[x.getUTCMonth()]}` : `${x.getUTCDate()} ${M.short[x.getUTCMonth()]}`)
  return {
    lang,
    t,
    /** 12 000 000 UZS */
    money: (n: number) => `${group(n)} ${CUR[lang]}`,
    /** 12M · 12 млн · 12 mln */
    mln: (n: number) => dec(n / 1e6) + MLN[lang],
    /** 12M UZS · 12 млн сум · 12 mln soʻm */
    mlnCur: (n: number) => `${dec(n / 1e6)}${MLN[lang]} ${CUR[lang]}`,
    cur: CUR[lang],
    dec,
    /** 15 Jun 2027 · 15 июн 2027 · 15-iyn 2027 */
    date: (iso: string) => `${day(d(iso))} ${d(iso).getUTCFullYear()}`,
    /** Wed 11 Nov, 14:00 */
    dateTime: (iso: string) => `${M.wd[d(iso).getUTCDay()]} ${day(d(iso))}, ${iso.slice(11, 16)}`,
    month: (iso: string) => M.long[d(iso).getUTCMonth()],
    monthShort: (iso: string) => M.short[d(iso).getUTCMonth()],
    role: (r?: Role | null) => (r ? (r.titleKey ? t(r.titleKey) : r.title ?? '') : ''),
  }
}
export type T = ReturnType<typeof makeT>

const cache: Partial<Record<Lang, T>> = {}
export function useT(): T {
  const lang = useStore((s) => s.lang)
  return (cache[lang] ??= makeT(lang))
}
export const currentT = (): T => {
  const lang = getState().lang
  return (cache[lang] ??= makeT(lang))
}
